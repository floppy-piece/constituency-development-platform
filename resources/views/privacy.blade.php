Constituency Portal – Privacy Policy

Effective Date: July 22, 2026

Last Updated: July 22, 2026
1. Introduction

Welcome to the Constituency Service Platform ("we," "our," or "us"). We provide a digital bridge connecting citizens with their elected Member of Parliament (MP) to submit community development requests, report issues, and monitor constituency projects.

We respect your privacy and are committed to protecting your personal data in accordance with local data protection laws and international messaging compliance standards (including Meta’s WhatsApp Business Policies). This Privacy Policy explains how we collect, use, process, and protect your information when you interact with our platform via website, dashboard, or WhatsApp.
2. Information We Collect

When you interact with our platform, we collect the following types of information:
A. Information Provided via WhatsApp (Citizens)

    Phone Number: Automatically collected when you send a message to our official WhatsApp Business number.

    Message Content: Text messages, voice notes, audio files, and photos submitted regarding constituency issues or requests.

    Metadata: Message timestamps and delivery status notifications.

B. Account Information (MPs and Platform Administrators)

    Login Credentials: Name, official email address, hashed passwords, and constituency assignment details.

3. How We Use Your Information

We process your data exclusively for legitimate civic and administrative purposes:

    Processing Requests: To receive, categorize, analyze, and track constituency development requests sent by citizens.

    AI Processing: Voice recordings and text messages are processed using automated translation and evaluation tools (such as Gemma AI models) to convert local languages/dialects into actionable summaries and assign urgency ratings.

    Automated Communication & Updates: To send automated receipt confirmations and rate-limiting notifications (e.g., maximum 1 request per 2 hours) via WhatsApp.

    Duplicate Prevention: To group similar requests (e.g., multiple citizens reporting the same broken bridge or pothole) to help MPs prioritize community issues.

4. How We Share Your Information

We do not sell, rent, or trade personal data to third parties for commercial or marketing purposes. Your data is shared strictly as needed to operate the service:

    Meta Platforms, Inc. (WhatsApp Cloud API): Messages sent via WhatsApp are processed through Meta's Cloud API infrastructure. Meta processes transit data securely in accordance with the Signal Protocol and Meta's Data Processing terms.

    Constituency Administrators & MPs: Authorized staff and elected representatives access submission summaries via the secure MP Portal to address civic concerns.

5. Third-Party API Services (Meta / WhatsApp Cloud API)

Our service integrates directly with the WhatsApp Cloud API provided by Meta Platforms, Inc.

    Personal WhatsApp conversations remain protected by standard transit encryption protocols.

    Data received via our WhatsApp webhook is handled strictly according to Meta's WhatsApp Business Messaging Policy and WhatsApp Terms of Service.

6. Data Storage and Retention

    Storage Security: All database entries and uploaded media are stored on secured, encrypted servers with strict access controls.

    Retention Limits: Raw media files (audio/images) and message transcripts are retained only for as long as necessary to address the reported constituency issue or as required by public record keeping standards.

7. Your Rights & Data Deletion

You have full control over your personal data:

    Opt-Out: You can stop interacting with our WhatsApp service at any time simply by refraining from sending messages or texting "STOP".

    Request Access or Deletion: Citizens can request the erasure or inspection of their phone number and submission history by contacting our administration team.

8. Data Security Measures

We implement industry-standard security measures to safeguard your information:

    Webhook Signature Verification: Every incoming request from Meta is validated using HMAC SHA-256 signatures (X-Hub-Signature-256) to prevent spoofing.

    Rate Limiting: Automated rate limits protect our infrastructure and prevent spamming.

    Access Control: Dashboard access is restricted via JWT / Session authentication and encrypted passwords.

9. Contact Us

If you have questions, concerns, or requests regarding this Privacy Policy or how your data is handled, please contact us:

    Email: support@your-constituency-domain.com

    Official Website: https://your-domain.com    

